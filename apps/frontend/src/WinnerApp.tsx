function isNewMarket(m: OriginMarket): boolean {
  if (!m.lifecycle.observedAt) return false;
  const ageMs = Date.now() - new Date(m.lifecycle.observedAt).getTime();
  return (m.lifecycle.status === "NEW" || m.lifecycle.status === "DISCOVERED") && Number.isFinite(ageMs) && ageMs >= 0 && ageMs < 14 * 86400000;
}

function isBondingMarket(m: OriginMarket): boolean {
  return ["BONDING", "BONDED"].includes(m.lifecycle.status);
}

function isGraduatedMarket(m: OriginMarket): boolean {
  return ["GRADUATED", "MIGRATED"].includes(m.lifecycle.status);
}

